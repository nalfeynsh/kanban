-- ============================================================
--  «Мой Канбан» — миграция 002: Telegram в профиле
--  Минимальный скрипт, если нужен только Telegram (без остальных
--  полей из 001). Идемпотентен — можно запускать повторно.
--
--  Supabase → SQL Editor → вставить → Run.
-- ============================================================

alter table public.profiles
  add column if not exists telegram text;

-- Проверка: колонка появилась
select column_name, data_type
from information_schema.columns
where table_schema = 'public'
  and table_name = 'profiles'
  and column_name = 'telegram';

